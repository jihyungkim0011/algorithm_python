# 북0 동1 남2 서3
dr = [-1, 0, 1, 0]
dc = [0, 1, 0, -1]

# 한점에서 모든 분기 탐색한다 -> BFS
# 큐에 넣어서 탐색.

# 답이 틀렸었던 이유: 왼쪽을 돌면서 갈 수 있는 방향을 탐색하되,
# 갈 곳이 없다면 다시 원래 방향으로 위치시켜야 한다.


def direction_when_go_back(d):
    return (d + 2) % 4

def direction_when_rotate_to_left(d):
    return (d + 3) % 4


def get_count_of_departments_cleaned_by_robot_vacuum(r, c, d, room_map):
    room_map[r][c] = 2
    count_clean = 1

    queue = deque([[r,c,d]])
    while queue:
        r, c, d = queue.popleft()
        d_temp = d

        # 동서남북을 탐색한다.
        for i in range(4):
            d_temp = direction_when_rotate_to_left(d_temp)
            r_next, c_next = r + dr[d_temp], c + dc[d_temp]

            # 빈공간 발견 시 전진
            if room_map[r_next][c_next] == 0:
                room_map[r_next][c_next] = 2
                count_clean += 1
                queue.append([r_next, c_next, d_temp])
                break # 이동했으므로 for 멈추고 while 반복

            elif i == 3:
                r_next, c_next = r + dr[direction_when_go_back(d)], c + dc[direction_when_go_back(d)],
                queue.append([r_next, c_next, d])

                if room_map[r_next][c_next] == 1:
                    return count_clean







print("정답 = 57 / 현재 풀이 값 = ",get_count_of_departments_cleaned_by_robot_vacuum(current_r, current_c, current_d, current_room_map))

